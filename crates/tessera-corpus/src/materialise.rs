//! The four materialisers (spec §12.1): the same corpus, written into each of Tessera's ways in.
//!
//! One source feeding every entry point is what makes an ingested item checkable against the same
//! function as a built one. [`Corpus::write_points_parquet`] and [`Corpus::write_pairs_parquet`]
//! are the build's two inputs; [`Corpus::config_toml`] is the declaration `tessera build --config`
//! compiles; [`Corpus::ingest_batch`] is `/control/ingest`'s body, in the **wire** shape —
//! `(external_id, x, y, access, the declared scalars)` — and deliberately not any engine type.
//! The executor's `UnallocatedRow` carries resolved term ids and a view, is constructed after
//! admission, and lives in a crate §13 forbids: a corpus that could speak it would have stopped
//! being a second statement of the corpus.
//!
//! Values agree across materialisers by construction — every writer calls [`Corpus::item`] and
//! [`Corpus::terms`], never a private variant of them — and the parquet writers stream in bounded
//! chunks because `n` may be 10⁹ while this process's memory is not.

