use parquet::arrow::ArrowWriter;

use crate::Corpus;

/// Rows per streamed chunk: 2¹⁶ rows keeps every builder's transient a few megabytes while giving
/// the parquet writer full row groups to accumulate.
const CHUNK_ROWS: u64 = 1 << 16;

/// The layer and level ids the artifact fixture's closed-form arms are materialised against —
/// arbitrary but fixed, so [`Corpus::write_artifact_fixtures`] and [`CONFIG_TOML`]'s five
/// `[[layer]]` blocks agree on which arm feeds which file without a layer id column anywhere on
/// disk. `FIXTURE_LEVEL` is level 0 — not [`crate::artifacts::EMPTY_LEVEL`] — because the fixture
/// is for a build to serve, and a level with no artifacts is a Rust-level property test's case
/// ([`crate::artifacts`]'s own tests), not something the campaign's config needs a row for.
pub const FLAT_LAYER: u64 = 1;
pub const PARTITION_LAYER: u64 = 2;
pub const BOUNDARY_LAYER: u64 = 3;
pub const TREED_LAYER: u64 = 4;
pub const FIXTURE_LEVEL: u32 = 0;

