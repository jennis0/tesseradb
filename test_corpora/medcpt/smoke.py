# ------------------------------------------------------------------------------------ the source


def read_chunk(chunk: int, limit: int | None) -> tuple[list[str], dict]:
    """The chunk's PMIDs in **embedding row order**, and the article records keyed by PMID.

    `pmids_chunk_N.json` is the row order of `embeds_chunk_N.npy`; `pubmed_chunk_N.json` is a
    pretty-printed `{pmid: {...}}` object of 1.4 GB, decoded value by value rather than through
    `json.load` so the peak is the text plus one record (the probe's approach, kept).
    """
    pmids = json.loads((SHARE / f"pmids_chunk_{chunk}.json").read_text())
    if limit is not None:
        pmids = pmids[:limit]
    wanted = set(pmids)
    records = {}
    text = (SHARE / f"pubmed_chunk_{chunk}.json").read_text()
    dec = json.JSONDecoder()
    i = text.index("{") + 1
    n = len(text)
    while True:
        while i < n and text[i] in " \t\r\n,":
            i += 1
        if text[i] == "}":
            break
        key, i = dec.raw_decode(text, i)
        while text[i] in " \t\r\n":
            i += 1
        i += 1  # the colon
        while text[i] in " \t\r\n":
            i += 1
        val, i = dec.raw_decode(text, i)
        if key in wanted:
            records[key] = val
    return [str(p) for p in pmids], records


# --------------------------------------------------------------------------------- the geometry


def pca2(path: Path, rows: int) -> np.ndarray:
    """Two principal components of the first `rows` MedCPT vectors, memory-mapped.

    The covariance is accumulated in `float64` over blocks rather than materialising a centred
    copy of the matrix — 200,000 × 768 × 4 bytes is 614 MB and there is no reason to hold two.
    """
    vectors = np.load(path, mmap_mode="r")[:rows]
    total = np.zeros(vectors.shape[1], np.float64)
    for lo in range(0, rows, 20_000):
        total += vectors[lo : lo + 20_000].sum(axis=0, dtype=np.float64)
    mean = total / rows
    cov = np.zeros((vectors.shape[1], vectors.shape[1]), np.float64)
    for lo in range(0, rows, 20_000):
        block = vectors[lo : lo + 20_000].astype(np.float64) - mean
        cov += block.T @ block
    _, components = np.linalg.eigh(cov / rows)
    axes = components[:, ::-1][:, :2]  # eigh ascends; the two largest, in order
    out = np.empty((rows, 2), np.float64)
    for lo in range(0, rows, 20_000):
        out[lo : lo + 20_000] = (vectors[lo : lo + 20_000].astype(np.float64) - mean) @ axes
    return out


# ------------------------------------------------------------------------------- the declaration


def write_corpus_toml(out: Path) -> None:
    """The minimal declaration: one view, the access column, two indexed attributes, the layer.

    Deliberately smaller than the rung's — no second view, no clustering layer, no abstracts —
    because what is being proved here is the DAG layer and everything else is scenery.
    """
    (out / "corpus.toml").write_text(
        f"""# Generated by `test_corpora/medcpt/smoke.py`. The MeSH DAG layer on one chunk of the
# MedCPT / PubMed corpus, laid out by a 2-component PCA of the embedding. This is the *smoke*
# declaration and not the rung's: `prepare.py` writes that one.

[sources]
points                = "points.parquet"
{SOURCES_TOML}
[defaults]
source          = "points"
entity_id_field = "entity_id"

# One view. `extent = "auto"` fits the box to the coordinates as they are; the PCA output spans a
# few units either side of zero and a stated frame would put the whole chunk in one corner of the
# grid, clamped rather than refused.
[[view]]
name             = "knn"
title            = "PubMed (PCA-2)"
projection       = "none"
extent           = "auto"
source           = "points"
visibility       = "public"
point_visibility = {{ field = "branches", default = "public" }}

# **The access column is `branches`** — the MeSH top-level branch letters an article's resolved
# descriptors sit under, a synthetic compartment scheme over a real column as every rung of the
# ladder uses. An article with no resolved descriptor carries the single term `unindexed` rather
# than an empty list, so `default = "public"` never fires: a point falling through to the default
# is one nothing states a policy for, and 13% of this chunk would have done so.

[[attribute]]
name  = "pmid"
title = "PMID"
type  = "keyword"
index = true

[[attribute]]
name  = "title"
type  = "text"
index = true
{LAYER_TOML}"""
    )


