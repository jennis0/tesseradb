"""The MeSH layer, proved end to end on one chunk: inputs, a build, and the spread it draws.

This is not the rung. `prepare.py` is the rung and it belongs to the vectors track; this driver
exists to put `mesh.py` through `tessera build` and the viewer on a slice small enough to iterate
on, and to measure the two things the owner asked for — the module's throughput on a whole staged
chunk, and the share of the map a descriptor's members occupy, by depth.

    python -m test_corpora.medcpt.smoke --bench          # throughput over all of chunk 18
    python -m test_corpora.medcpt.smoke --out DIR        # write 200,000 articles' build inputs
    python -m test_corpora.medcpt.smoke --out DIR --spread   # after a build: the spread table

The geometry is a 2-component PCA of the MedCPT embedding rather than the rung's kNN/UMAP route.
It is real structure and not a placeholder — the same 768-dimensional vectors, projected — but it
is the *worse* of the two layouts by the arXiv rung's own measurement (`ingest-campaign.md` §4.5:
a cluster is 27–29 row runs in `pca64` against 3.5–4.1 in `knn`, and everything is "everywhere"),
so every spread figure below is a **lower bound on how well the layer draws**, not an estimate of
what the rung will show. Said here because a number measured on a PCA layout and quoted against a
UMAP one would be the wrong number twice over.
"""

